#!/usr/bin/env node
// Exports the AN3S design system for websites and apps.
// Reads project/tokens.json and the brand assets, and writes dist/web/:
//   tokens.css          every token as a CSS custom property (+ an -hsl channel copy of each colour)
//   shadcn.css          the design system mapped onto shadcn/ui roles (pink leads, cyan answers)
//   tailwind-preset.js  a Tailwind preset whose palette, fonts, radii and shadows are only these tokens
//   tokens.ts           typed values for code that can't read CSS (charts, canvas)
//   assets/             the wordmark and the service icons
//   manifest.json       source hash, Google Fonts URL and a hash of every file, for consumers' checks
//
//   node tools/export.mjs          write dist/web/
//   node tools/export.mjs --check  exit 1 if dist/web/ is stale or a role pairing fails contrast
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'dist', 'web');
const CHECK = process.argv.includes('--check');
const NOTE = 'Generated by tools/export.mjs from project/tokens.json. Do not edit: change the design system, then re-export.';

// Families served by Google Fonts. Every other named family in a stack is a local or system face.
const GOOGLE_FAMILIES = ['Montserrat'];

// shadcn/ui role -> design-system colour token. A design decision: pink leads, cyan answers,
// menus and hovers lift onto nebula, controls take line-strong edges.
const ROLES = {
  background: 'deep-space',
  foreground: 'ink',
  card: 'panel',
  'card-foreground': 'ink',
  popover: 'panel',
  'popover-foreground': 'ink',
  primary: 'pink',
  'primary-foreground': 'deep-space',
  secondary: 'cyan',
  'secondary-foreground': 'deep-space',
  muted: 'panel',
  'muted-foreground': 'ink-muted',
  accent: 'nebula',
  'accent-foreground': 'ink',
  destructive: 'danger',
  'destructive-foreground': 'on-danger',
  success: 'success',
  'success-foreground': 'on-success',
  border: 'line',
  input: 'line-strong',
  ring: 'focus',
  'chart-1': 'pink',
  'chart-2': 'cyan',
  'chart-3': 'blue',
  'chart-4': 'violet',
  'chart-5': 'ink',
  sidebar: 'panel',
  'sidebar-background': 'panel',
  'sidebar-foreground': 'ink',
  'sidebar-primary': 'pink',
  'sidebar-primary-foreground': 'deep-space',
  'sidebar-accent': 'nebula',
  'sidebar-accent-foreground': 'ink',
  'sidebar-border': 'line',
  'sidebar-ring': 'focus',
};

// [foreground role, background role, minimum WCAG ratio]: every pairing the roles promise.
const PAIRS = [
  ['foreground', 'background', 4.5],
  ['card-foreground', 'card', 4.5],
  ['popover-foreground', 'popover', 4.5],
  ['primary-foreground', 'primary', 4.5],
  ['secondary-foreground', 'secondary', 4.5],
  ['muted-foreground', 'muted', 4.5],
  ['muted-foreground', 'background', 4.5],
  ['accent-foreground', 'accent', 4.5],
  ['destructive-foreground', 'destructive', 4.5],
  ['success-foreground', 'success', 4.5],
  ['primary', 'background', 4.5],
  ['secondary', 'background', 4.5],
  ['destructive', 'background', 4.5],
  ['destructive', 'card', 4.5],
  ['success', 'background', 4.5],
  ['success', 'card', 4.5],
  ['ring', 'background', 3],
  ['ring', 'card', 3],
  ['input', 'background', 3],
  ['input', 'card', 3],
];

const tokensText = readFileSync(join(ROOT, 'project', 'tokens.json'), 'utf8');
const tokens = JSON.parse(tokensText);
const theme = tokens.color.themes[0].id;
const valueOf = (t) => (typeof t.value === 'string' ? t.value : t.value[theme]);

// ---------- colour maths ----------
const colors = new Map(tokens.color.tokens.map((t) => [t.name, valueOf(t)]));
const aliasOf = (v) => /^\{(.+)\}$/.exec(v)?.[1];

function resolve(name, seen = new Set()) {
  const v = colors.get(name);
  if (v === undefined) throw new Error(`Unknown colour token "${name}"`);
  const target = aliasOf(v);
  if (!target) return v;
  if (seen.has(name)) throw new Error(`Alias cycle at "${name}"`);
  seen.add(name);
  return resolve(target, seen);
}

function rgba(hex) {
  let h = hex.replace('#', '');
  if (!/^[0-9a-f]+$/i.test(h) || ![3, 4, 6, 8].includes(h.length)) throw new Error(`Only hex colours are exported, got "${hex}"`);
  if (h.length <= 4) h = [...h].map((c) => c + c).join('');
  const n = (i) => parseInt(h.slice(i, i + 2), 16);
  return { r: n(0), g: n(2), b: n(4), a: h.length === 8 ? n(6) / 255 : 1 };
}

const fixed = (x) => String(Number(x.toFixed(2)));

function hslChannels(hex) {
  const { r, g, b, a } = rgba(hex);
  const [R, G, B] = [r / 255, g / 255, b / 255];
  const max = Math.max(R, G, B);
  const min = Math.min(R, G, B);
  const l = (max + min) / 2;
  let h = 0;
  let s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === R) h = (G - B) / d + (G < B ? 6 : 0);
    else if (max === G) h = (B - R) / d + 2;
    else h = (R - G) / d + 4;
    h *= 60;
  }
  const base = `${fixed(h)} ${fixed(s * 100)}% ${fixed(l * 100)}%`;
  return a < 1 ? `${base} / ${fixed(a * 100)}%` : base;
}

function luminance(hex) {
  const { r, g, b } = rgba(hex);
  const f = (c) => {
    const v = c / 255;
    return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
}

// A translucent colour measured where it lands: composited over its ground.
function over(hex, ground) {
  const c = rgba(hex);
  const g = rgba(ground);
  const mix = (x, y) => Math.round(x * c.a + y * (1 - c.a));
  return `#${[mix(c.r, g.r), mix(c.g, g.g), mix(c.b, g.b)].map((v) => v.toString(16).padStart(2, '0')).join('')}`;
}

function contrast(fg, bg) {
  const a = luminance(over(fg, bg)) + 0.05;
  const b = luminance(bg) + 0.05;
  return Math.max(a, b) / Math.min(a, b);
}

const isTranslucent = (name) => rgba(resolve(name)).a < 1;

// ---------- outputs ----------
function tokensCss() {
  const out = [`/* AN3S design system: every token as a CSS custom property. ${NOTE} */`, ':root {'];
  for (const t of tokens.color.tokens) {
    const raw = valueOf(t);
    const target = aliasOf(raw);
    if (target) out.push(`  --${t.name}: var(--${target});`, `  --${t.name}-hsl: var(--${target}-hsl);`);
    else out.push(`  --${t.name}: ${raw};`, `  --${t.name}-hsl: ${hslChannels(raw)};`);
  }
  for (const family of ['shadow', 'spacing', 'radius', 'gradient', 'size']) {
    for (const t of tokens[family]?.tokens ?? []) out.push(`  --${t.name}: ${valueOf(t)};`);
  }
  for (const [key, stack] of Object.entries(tokens.type.families)) out.push(`  --font-${key}: ${stack};`);
  out.push('}', '');
  for (const group of tokens.type.groups) {
    for (const s of group.styles) {
      const decl = [
        `font-family: var(--font-${s.family || group.family})`,
        `font-size: ${s.fontSize}`,
        `line-height: ${s.lineHeight}`,
        `font-weight: ${s.fontWeight}`,
      ];
      if (s.letterSpacing) decl.push(`letter-spacing: ${s.letterSpacing}`);
      out.push(`.type-${s.name} { ${decl.join('; ')}; }`);
    }
  }
  return `${out.join('\n')}\n`;
}

function shadcnCss() {
  const out = [`/* AN3S design system mapped onto shadcn/ui roles: pink leads, cyan answers. ${NOTE} */`, ':root {'];
  for (const [role, token] of Object.entries(ROLES)) out.push(`  --${role}: var(--${token}-hsl);`);
  out.push('  --radius: var(--radius-lg);', '}');
  return `${out.join('\n')}\n`;
}

function presetJs() {
  const tokenColor = (name) => (isTranslucent(name) ? `hsl(var(--${name}-hsl))` : `hsl(var(--${name}-hsl) / <alpha-value>)`);
  const roleColor = (role) => (isTranslucent(ROLES[role]) ? `hsl(var(--${role}))` : `hsl(var(--${role}) / <alpha-value>)`);
  const palette = {
    transparent: 'transparent',
    current: 'currentColor',
    inherit: 'inherit',
    black: tokenColor('void'),
    white: tokenColor('ink'),
  };
  for (const t of tokens.color.tokens) palette[t.name] = tokenColor(t.name);
  Object.assign(palette, {
    border: roleColor('border'),
    input: roleColor('input'),
    ring: roleColor('ring'),
    background: roleColor('background'),
    foreground: roleColor('foreground'),
    primary: { DEFAULT: roleColor('primary'), foreground: roleColor('primary-foreground') },
    secondary: { DEFAULT: roleColor('secondary'), foreground: roleColor('secondary-foreground') },
    destructive: { DEFAULT: roleColor('destructive'), foreground: roleColor('destructive-foreground') },
    success: { DEFAULT: roleColor('success'), foreground: roleColor('success-foreground') },
    muted: { DEFAULT: roleColor('muted'), foreground: roleColor('muted-foreground') },
    accent: { DEFAULT: roleColor('accent'), foreground: roleColor('accent-foreground') },
    popover: { DEFAULT: roleColor('popover'), foreground: roleColor('popover-foreground') },
    card: { DEFAULT: roleColor('card'), foreground: roleColor('card-foreground') },
    chart: Object.fromEntries([1, 2, 3, 4, 5].map((i) => [String(i), roleColor(`chart-${i}`)])),
    sidebar: {
      DEFAULT: roleColor('sidebar-background'),
      foreground: roleColor('sidebar-foreground'),
      primary: roleColor('sidebar-primary'),
      'primary-foreground': roleColor('sidebar-primary-foreground'),
      accent: roleColor('sidebar-accent'),
      'accent-foreground': roleColor('sidebar-accent-foreground'),
      border: roleColor('sidebar-border'),
      ring: roleColor('sidebar-ring'),
    },
  });

  const fontSize = {};
  for (const group of tokens.type.groups) {
    for (const s of group.styles) {
      const meta = { lineHeight: s.lineHeight, fontWeight: String(s.fontWeight) };
      if (s.letterSpacing) meta.letterSpacing = s.letterSpacing;
      fontSize[s.name] = [s.fontSize, meta];
    }
  }
  const vars = (family) => Object.fromEntries((tokens[family]?.tokens ?? []).map((t) => [t.name, `var(--${t.name})`]));
  const sizes = vars('size');
  const radius = (name) => `var(--${name})`;
  const glows = Object.fromEntries((tokens.shadow?.tokens ?? []).map((t) => [t.name, `var(--${t.name})`]));

  const preset = {
    theme: {
      colors: palette,
      fontFamily: Object.fromEntries([
        ...Object.keys(tokens.type.families).map((key) => [key, `var(--font-${key})`]),
        ['heading', 'var(--font-sans)'],
      ]),
      borderRadius: {
        none: '0',
        sm: radius('radius-sm'),
        DEFAULT: radius('radius-sm'),
        md: radius('radius-md'),
        lg: radius('radius-lg'),
        xl: radius('radius-lg'),
        '2xl': radius('radius-lg'),
        '3xl': radius('radius-lg'),
        full: radius('radius-full'),
      },
      // Depth comes from light, not shadow: the stock drop shadows render as nothing.
      boxShadow: {
        none: 'none',
        sm: 'none',
        DEFAULT: 'none',
        md: 'none',
        lg: 'none',
        xl: 'none',
        '2xl': 'none',
        inner: 'none',
        ...glows,
      },
      extend: {
        backgroundImage: vars('gradient'),
        fontSize,
        spacing: vars('spacing'),
        maxWidth: { measure: sizes.measure },
        minHeight: { control: sizes.control },
        height: { control: sizes.control, 'icon-tile': sizes['icon-tile'], 'icon-inline': sizes['icon-inline'] },
        width: { 'icon-tile': sizes['icon-tile'], 'icon-inline': sizes['icon-inline'] },
      },
    },
  };
  return `// AN3S Tailwind preset: the palette, fonts, radii and shadows are only design-system tokens.\n// ${NOTE}\n/** @type {import('tailwindcss').Config} */\nexport default ${JSON.stringify(preset, null, 2)};\n`;
}

function googleFontsHref() {
  const families = [];
  for (const [key, stack] of Object.entries(tokens.type.families)) {
    const first = stack.split(',').map((f) => f.trim().replace(/^["']|["']$/g, '')).find((f) => GOOGLE_FAMILIES.includes(f));
    if (!first) continue;
    const weights = new Set();
    for (const group of tokens.type.groups) {
      for (const s of group.styles) if ((s.family || group.family) === key) weights.add(Number(s.fontWeight));
    }
    families.push(`family=${first.replace(/ /g, '+')}:wght@${[...weights].sort((a, b) => a - b).join(';')}`);
  }
  return `https://fonts.googleapis.com/css2?${families.join('&')}&display=swap`;
}

function tokensTs(href) {
  const obj = (family) => Object.fromEntries((tokens[family]?.tokens ?? []).map((t) => [t.name, valueOf(t)]));
  const typeStyles = {};
  for (const group of tokens.type.groups) {
    for (const s of group.styles) {
      typeStyles[s.name] = {
        fontFamily: tokens.type.families[s.family || group.family],
        fontSize: s.fontSize,
        lineHeight: s.lineHeight,
        fontWeight: s.fontWeight,
        ...(s.letterSpacing ? { letterSpacing: s.letterSpacing } : {}),
      };
    }
  }
  const lit = (v) => JSON.stringify(v, null, 2);
  return [
    `// AN3S design tokens as typed values, for code that can't read CSS custom properties (charts, canvas).`,
    `// Colours are resolved to hex (aliases followed). ${NOTE}`,
    '',
    `export const color = ${lit(Object.fromEntries(tokens.color.tokens.map((t) => [t.name, resolve(t.name)])))} as const;`,
    '',
    `export const shadow = ${lit(obj('shadow'))} as const;`,
    '',
    `export const gradient = ${lit(obj('gradient'))} as const;`,
    '',
    `export const space = ${lit(obj('spacing'))} as const;`,
    '',
    `export const radius = ${lit(obj('radius'))} as const;`,
    '',
    `export const size = ${lit(obj('size'))} as const;`,
    '',
    `export const font = ${lit(tokens.type.families)} as const;`,
    '',
    `export const typeStyle = ${lit(typeStyles)} as const;`,
    '',
    `export const googleFontsHref = ${JSON.stringify(href)};`,
    '',
    'export type ColorToken = keyof typeof color;',
    'export type TypeStyle = keyof typeof typeStyle;',
    '',
  ].join('\n');
}

function readmeMd(href) {
  return [
    '# AN3S design system: web export',
    '',
    NOTE,
    '',
    'Copy this folder into a website as-is and record it with its `manifest.json`. A consumer:',
    '',
    '- imports `tokens.css`, then `shadcn.css`, before its own styles;',
    '- loads its Tailwind config through `tailwind-preset.js`, so the palette, fonts, radii and shadows are only these tokens (the stock Tailwind colours and drop shadows are gone);',
    `- loads the fonts from ${href};`,
    '- imports `tokens.ts` where code needs raw values (charts, canvas);',
    '- takes the wordmark and icons from `assets/`;',
    '- verifies its copy against the hashes in `manifest.json` (CRLF normalised to LF for text files).',
    '',
    'Rules for using the tokens (which colour leads, when to glow, type casing) live in the design system\'s brand book, `project/README.md`.',
    '',
  ].join('\n');
}

// ---------- assets ----------
const ASSETS = [
  ['project/assets/Logos/an3s-wordmark.png', 'assets/an3s-wordmark.png'],
  ['project/assets/Logos/an3s-wordmark-on-space.png', 'assets/an3s-wordmark-on-space.png'],
  ...readdirSync(join(ROOT, 'project', 'assets', 'Icons'))
    .filter((f) => f.endsWith('.svg'))
    .sort()
    .map((f) => [`project/assets/Icons/${f}`, `assets/icons/${f}`]),
];

// ---------- build, verify, write ----------
const TEXT = /\.(css|js|ts|json|md|svg)$/;
const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const normalized = (rel, buf) => (TEXT.test(rel) ? Buffer.from(buf.toString('utf8').replace(/\r\n/g, '\n')) : buf);

const href = googleFontsHref();
const files = new Map([
  ['README.md', Buffer.from(readmeMd(href))],
  ['tokens.css', Buffer.from(tokensCss())],
  ['shadcn.css', Buffer.from(shadcnCss())],
  ['tailwind-preset.js', Buffer.from(presetJs())],
  ['tokens.ts', Buffer.from(tokensTs(href))],
]);
for (const [src, rel] of ASSETS) files.set(rel, readFileSync(join(ROOT, src)));

const manifest = {
  name: tokens.name ?? 'AN3S',
  note: NOTE,
  tokensSha256: sha256(normalized('tokens.json', Buffer.from(tokensText))),
  googleFontsHref: href,
  roles: ROLES,
  files: Object.fromEntries([...files].map(([rel, buf]) => [rel, sha256(normalized(rel, buf))])),
};
files.set('manifest.json', Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`));

// Every pairing the role mapping promises must hold.
const roleValue = (role) => resolve(ROLES[role]);
const failures = [];
for (const [fg, bg, min] of PAIRS) {
  const ratio = contrast(roleValue(fg), roleValue(bg));
  if (ratio < min) failures.push(`${fg} on ${bg}: ${ratio.toFixed(2)}:1, needs ${min}:1`);
}
if (failures.length) {
  console.error(`Contrast failures in the role mapping:\n  ${failures.join('\n  ')}`);
  process.exit(1);
}

if (CHECK) {
  const stale = [];
  for (const [rel, buf] of files) {
    const path = join(OUT, rel);
    if (!existsSync(path) || sha256(normalized(rel, readFileSync(path))) !== sha256(normalized(rel, buf))) stale.push(rel);
  }
  if (stale.length) {
    console.error(`dist/web is stale; run node tools/export.mjs. Stale: ${stale.join(', ')}`);
    process.exit(1);
  }
  console.log(`dist/web is current (${files.size} files); ${PAIRS.length} role pairings pass contrast.`);
} else {
  for (const [rel, buf] of files) {
    mkdirSync(dirname(join(OUT, rel)), { recursive: true });
    writeFileSync(join(OUT, rel), buf);
  }
  console.log(`Wrote ${files.size} files to dist/web; ${PAIRS.length} role pairings pass contrast.`);
}
