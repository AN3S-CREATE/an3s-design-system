#!/usr/bin/env node
// Builds the AN3S brand graphics from tools/brand/geometry.mjs and the colour tokens:
//
//   project/assets/Logos/an3s-wordmark.svg       the wordmark with its glow (the default logo)
//   project/assets/Logos/an3s-wordmark-flat.svg  the wordmark without glow (small sizes, single-layer uses)
//   project/assets/Logos/an3s-loader.svg         the wordmark whose glow breathes (loading screens)
//   project/assets/Logos/an3s-mark.svg           square mark: the pink 3 on a deep-space tile (favicon)
//   project/assets/Logos/an3s-mark-180.png       apple-touch-icon (opaque square)
//   project/assets/Logos/an3s-mark-512.png       app manifests and structured-data logos
//   project/assets/Imagery/an3s-share.png        1200 x 630 link-preview image (og:image)
//
// No favicon.ico: the artifact's asset store takes no .ico, and current browsers read the SVG mark.
//
// Usage: node tools/brand/build.mjs          rebuild everything
//        node tools/brand/build.mjs --svg    rebuild the SVGs only (no browser needed)
//
// PNG renders use headless Chrome or Edge: set CHROME to its path if it isn't in a default
// location. The share image also loads Montserrat from Google Fonts and React from jsDelivr, so it
// needs a network connection. After a rebuild, run `node tools/export.mjs` to refresh dist/web/.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { BOX, GLYPHS } from './geometry.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const LOGOS = join(ROOT, 'project', 'assets', 'Logos');
const IMAGERY = join(ROOT, 'project', 'assets', 'Imagery');

// ---------- tokens ----------
const tokens = JSON.parse(readFileSync(join(ROOT, 'project', 'tokens.json'), 'utf8'));
const colours = Object.fromEntries(tokens.color.tokens.map((t) => [t.name, t.value]));
const colour = (name) => {
  let v = colours[name];
  while (v && v.startsWith('{')) v = colours[v.slice(1, -1)];
  if (!/^#[0-9a-f]{6}$/i.test(v || '')) throw new Error(`token ${name} is not an opaque hex colour: ${v}`);
  return v.toLowerCase();
};
const C = { ink: colour('ink'), pink: colour('pink'), cyan: colour('cyan'), space: colour('deep-space') };

// ---------- SVG ----------
const n = (v) => +v.toFixed(2);
const PAD = 16; // room for the glow around the ink box
const INK = { x: BOX.x0 - 0.375, y: BOX.y0 - 0.4, w: 344, h: 91 }; // ink box, 0.4 clear on every side

// The four letters as a group, indented by `pad`; `attrs` go on the <g>.
const letters = (pad, attrs) => [
  `${pad}<g ${attrs}>`,
  `${pad}  <path fill="${C.ink}" d="${GLYPHS.A}"/>`,
  `${pad}  <path fill="${C.ink}" d="${GLYPHS.N}"/>`,
  `${pad}  <path fill="${C.pink}" d="${GLYPHS.three}"/>`,
  `${pad}  <path fill="${C.cyan}" d="${GLYPHS.S}"/>`,
  `${pad}</g>`,
].join('\n');

// The glow: a tight halo (blur 2.5) over a wide bloom (blur 9 at 80%), both in each letter's own colour.
const glowFilter = (id, bloom = true) => [
  `<filter id="${id}" x="-10%" y="-30%" width="120%" height="160%" color-interpolation-filters="sRGB">`,
  '      <feGaussianBlur in="SourceGraphic" stdDeviation="2.5" result="tight"/>',
  ...(bloom ? [
    '      <feGaussianBlur in="SourceGraphic" stdDeviation="9" result="wide"/>',
    '      <feComponentTransfer in="wide" result="bloom"><feFuncA type="linear" slope="0.8"/></feComponentTransfer>',
  ] : []),
  `      <feMerge>${bloom ? '<feMergeNode in="bloom"/>' : ''}<feMergeNode in="tight"/><feMergeNode in="SourceGraphic"/></feMerge>`,
  '    </filter>',
].join('\n');

const head = (viewBox, w, h, title, note) => [
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${w}" height="${h}" role="img" aria-label="${title}">`,
  `  <!-- ${note} Generated by tools/brand/build.mjs: edit the geometry or tokens, not this file. -->`,
  `  <title>${title}</title>`,
];

const glowBox = `${n(INK.x - PAD)} ${n(INK.y - PAD)} ${INK.w + 2 * PAD} ${INK.h + 2 * PAD}`;

function wordmarkSvg() {
  return [
    ...head(glowBox, INK.w + 2 * PAD, INK.h + 2 * PAD, 'AN3S',
      'AN3S wordmark with its glow. AN in ink, 3 in pink, S in cyan; for deep-space, void, panel and Starfield grounds.'),
    '  <defs>',
    `    ${glowFilter('an3s-wordmark-glow')}`,
    '  </defs>',
    letters('  ', 'filter="url(#an3s-wordmark-glow)"'),
    '</svg>',
    '',
  ].join('\n');
}

function flatSvg() {
  return [
    ...head(`${INK.x} ${INK.y} ${INK.w} ${INK.h}`, INK.w, INK.h, 'AN3S',
      'AN3S wordmark without glow, for small sizes and single-layer uses. Same ground rules as the glowing wordmark.'),
    letters('  ', 'id="an3s-wordmark-flat-letters"'),
    '</svg>',
    '',
  ].join('\n');
}

// Loader: the glowing wordmark with a wide bloom that swells by a third over 4s (brand book, Motion).
// The resting opacity is an attribute, not CSS: sanitizers that strip <style> (the artifact's asset
// store does) then leave a still loader at the right glow instead of a full-strength bloom.
function loaderSvg() {
  return [
    ...head(glowBox, INK.w + 2 * PAD, INK.h + 2 * PAD, 'AN3S',
      'AN3S loading mark: the glowing wordmark, its bloom breathing over 4s; still under prefers-reduced-motion.'),
    '  <style>',
    '    .an3s-loader-bloom { animation: an3s-loader-breathe 4s ease-in-out infinite alternate; }',
    '    @keyframes an3s-loader-breathe { from { opacity: 0.6; } to { opacity: 0.8; } }',
    '    @media (prefers-reduced-motion: reduce) { .an3s-loader-bloom { animation: none; } }',
    '  </style>',
    '  <defs>',
    letters('    ', 'id="an3s-loader-letters"'),
    `    <filter id="an3s-loader-wide" x="-10%" y="-30%" width="120%" height="160%" color-interpolation-filters="sRGB"><feGaussianBlur stdDeviation="9"/></filter>`,
    `    ${glowFilter('an3s-loader-glow', false)}`,
    '  </defs>',
    '  <use class="an3s-loader-bloom" opacity="0.6" href="#an3s-loader-letters" filter="url(#an3s-loader-wide)"/>',
    '  <use href="#an3s-loader-letters" filter="url(#an3s-loader-glow)"/>',
    '</svg>',
    '',
  ].join('\n');
}

// Mark: the 3 of the wordmark, pink on a deep-space tile with radius-lg proportions.
const MARK = 128;
function markSvg() {
  const x0 = 180.1, x1 = 256.7, y0 = BOX.y0, y1 = 108.6; // ink box of the 3
  const s = 80 / (y1 - y0);
  const tx = n(MARK / 2 - ((x0 + x1) / 2) * s), ty = n(MARK / 2 - ((y0 + y1) / 2) * s);
  return [
    ...head(`0 0 ${MARK} ${MARK}`, MARK, MARK, 'AN3S',
      'AN3S mark: the pink 3 of the wordmark on a deep-space tile. Favicons, app icons and avatars.'),
    '  <defs>',
    '    <filter id="an3s-mark-glow" x="-30%" y="-30%" width="160%" height="160%" color-interpolation-filters="sRGB">',
    '      <feGaussianBlur in="SourceGraphic" stdDeviation="3" result="blur"/>',
    '      <feMerge><feMergeNode in="blur"/><feMergeNode in="SourceGraphic"/></feMerge>',
    '    </filter>',
    '  </defs>',
    `  <rect width="${MARK}" height="${MARK}" rx="28" fill="${C.space}"/>`,
    `  <path fill="${C.pink}" filter="url(#an3s-mark-glow)" transform="translate(${tx} ${ty}) scale(${n(s * 1000) / 1000})" d="${GLYPHS.three}"/>`,
    '</svg>',
    '',
  ].join('\n');
}

// ---------- headless Chrome ----------
function findChrome() {
  const candidates = [
    process.env.CHROME,
    'C:/Program Files/Google/Chrome/Application/chrome.exe',
    'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    '/usr/bin/google-chrome',
    '/usr/bin/chromium',
  ].filter(Boolean);
  const found = candidates.find((p) => existsSync(p));
  if (!found) throw new Error('No Chrome or Edge found: set CHROME to its path.');
  return found;
}

function screenshot(html, width, height, out, { transparent = true, wait = 0 } = {}) {
  const dir = mkdtempSync(join(tmpdir(), 'an3s-brand-'));
  try {
    const page = join(dir, 'page.html');
    writeFileSync(page, html);
    const args = [
      '--headless=new', '--disable-gpu', '--hide-scrollbars', '--no-first-run', '--disable-extensions',
      `--user-data-dir=${join(dir, 'profile')}`, '--force-device-scale-factor=1',
      `--window-size=${width},${height}`, `--screenshot=${out}`,
    ];
    if (transparent) args.push('--default-background-color=00000000');
    if (wait) args.push(`--virtual-time-budget=${wait}`);
    args.push(pathToFileURL(page).href);
    execFileSync(findChrome(), args, { stdio: 'pipe' });
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const imagePage = (svg, size, ground) =>
  `<!doctype html><html><head><meta charset="utf-8"><style>html,body{margin:0;background:${ground}}img{display:block;width:${size}px;height:${size}px}</style></head>` +
  `<body><img src="data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}"></body></html>`;

function renderMark(svg, size, out, ground = 'transparent') {
  screenshot(imagePage(svg, size, ground), size, size, out, { transparent: ground === 'transparent' });
}

// Share image: the key visual's right-hand column on a Starfield, built from the system's own components.
function sharePage(wordmark) {
  const tokensCss = readFileSync(join(ROOT, 'dist', 'web', 'tokens.css'), 'utf8');
  const typeAliases = tokensCss.split('\n').filter((l) => l.startsWith('.type-')).map((l) => l.replace('.type-', '.')).join('\n');
  const file = (p) => pathToFileURL(join(ROOT, p)).href;
  return `<!doctype html><html lang="en"><head><meta charset="utf-8">
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Montserrat:wght@300;400;500;600;700;800&display=block">
<link rel="stylesheet" href="${file('dist/web/tokens.css')}">
<style>${typeAliases}</style>
<link rel="stylesheet" href="${file('project/components/bundle.css')}">
<style>
  html, body { width: 1200px; height: 630px; overflow: hidden; }
  .an3s-starfield { height: 630px; }
  .share { box-sizing: border-box; height: 630px; display: flex; flex-direction: column; align-items: center; justify-content: center; gap: var(--space-5); padding: var(--space-7) var(--space-8); text-align: center; }
  .share .an3s-statement { max-width: 880px; margin: 0; }
  .mark { display: block; width: 560px; height: auto; margin: calc(-1 * var(--space-4)) 0; }
</style>
<script src="https://cdn.jsdelivr.net/npm/react@18.3.1/umd/react.production.min.js"></script>
<script src="https://cdn.jsdelivr.net/npm/react-dom@18.3.1/umd/react-dom.production.min.js"></script>
<script src="${file('project/components/bundle.js')}"></script>
</head><body><div id="root"></div>
<script>
  var A = window.AN3S, h = React.createElement;
  ReactDOM.createRoot(document.getElementById('root')).render(h(A.Starfield, { seed: 11, minHeight: 630 },
    h('div', { className: 'share' },
      h(A.NameLockup, { first: 'Andries', last: 'Liebenberg', align: 'center', size: 44 }),
      h('img', { className: 'mark', alt: 'AN3S', src: 'data:image/svg+xml;base64,${Buffer.from(wordmark).toString('base64')}' }),
      h(A.Statement, null, h(A.Highlight, { tone: 'pink' }, 'Strategic'), ' Development &', h('br'),
        h(A.Highlight, { tone: 'cyan' }, 'Growth Advisor'), ' for Intelligent Businesses'))));
</script></body></html>`;
}

// ---------- build ----------
const svgOnly = process.argv.includes('--svg');
const wordmark = wordmarkSvg();
const mark = markSvg();
const outputs = {
  [join(LOGOS, 'an3s-wordmark.svg')]: wordmark,
  [join(LOGOS, 'an3s-wordmark-flat.svg')]: flatSvg(),
  [join(LOGOS, 'an3s-loader.svg')]: loaderSvg(),
  [join(LOGOS, 'an3s-mark.svg')]: mark,
};
for (const [path, text] of Object.entries(outputs)) writeFileSync(path, text);
console.log(`wrote ${Object.keys(outputs).length} SVGs`);

if (!svgOnly) {
  renderMark(mark, 180, join(LOGOS, 'an3s-mark-180.png'), C.space);
  renderMark(mark, 512, join(LOGOS, 'an3s-mark-512.png'));
  screenshot(sharePage(wordmark), 1200, 630, join(IMAGERY, 'an3s-share.png'), { transparent: false, wait: 15000 });
  console.log('rendered an3s-mark-180.png, an3s-mark-512.png, an3s-share.png');
}
